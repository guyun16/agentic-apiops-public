import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import fs from 'node:fs'
import { categoryRows, failureGroups, filterTasks, outcome, formatMetric } from './benchmarkViewModel.ts'
const r = JSON.parse(fs.readFileSync(new URL('./final-result.snapshot.json', import.meta.url),'utf8'))
const summary = JSON.parse(fs.readFileSync(new URL('./final-result.summary.json', import.meta.url),'utf8'))
assert.equal(r.revision,'stage21-formal105-final-closure-v5')
assert.equal(r.evaluationRunId,'evaluation_run:stage21-real-model-full-105-20260905T054023Z')
assert.equal(summary.benchmarkRevision,r.revision)
assert.equal(summary.evaluationRunId,r.evaluationRunId)
assert.equal(r.sourceKind,'VERIFIED_ARTIFACT_SNAPSHOT')
assert.deepEqual(r.outcomes,{FAIL:9,PASS:95,UNKNOWN:1})
assert.deepEqual([r.passRate,r.outcomeAccuracy,r.unknownRate].map(v=>(v*100).toFixed(2)),['90.48','91.35','0.95'])
assert.equal(r.acceptance,'PASS_WITH_LIMITATIONS')
assert.ok(r.gates.every(gate=>gate.passed && gate.threshold===0.85))
assert.equal(r.tasks.length,105)
assert.ok(r.tasks.every(task=>task.evaluationRunId===r.evaluationRunId && task.formalOutcome.revision===r.revision))
const counts = list => Object.fromEntries(['FAIL','PASS','UNKNOWN'].map(status=>[status,list.filter(task=>outcome(task)===status).length]))
assert.deepEqual(counts(r.tasks),r.outcomes)
assert.equal(r.detail.taskSuccess.passCount,58,'Legacy v1 data stays diagnostic, not rewritten to official v2')
assert.ok(r.tasks.every(task=>task.status==='SUCCESS'),'Runtime SUCCESS must coexist with formal FAIL/UNKNOWN')
for (const [name,split] of Object.entries(r.splits)) {
  const tasks=r.tasks.filter(task=>task.formalOutcome.split===name.toLowerCase())
  assert.equal(tasks.length,split.taskCount)
  assert.deepEqual(counts(tasks),{FAIL:split.v2Outcome.FAIL,PASS:split.v2Outcome.PASS,UNKNOWN:split.v2Outcome.UNKNOWN??0})
}
assert.deepEqual(Object.values(r.published.splitPassRate).map(v=>(v*100).toFixed(2)),['90.53','90.00'])
const reproducibilityPath = new URL('../../../../' + r.reproducibility.source, import.meta.url)
const reproducibilityBytes = fs.readFileSync(reproducibilityPath)
const reproducibilityArtifact = JSON.parse(reproducibilityBytes)
assert.deepEqual(Object.keys(reproducibilityArtifact).sort(), ['artifactInventory','dataset','environmentReadiness','exactCommand','execution','inventoryExcludes','policy','prompt','provider','rag','runtime','schemaVersion','source'])
assert.equal(r.reproducibility.status,'NOT VERIFIED')
assert.match(r.reproducibility.reason,/no overall reproducibility gate verdict/)
assert.ok(!('reproducibility' in r.published),'A user statement must not supply reproducibility status')
assert.equal(r.sources.find(source=>source.path===r.reproducibility.source)?.sha256,crypto.createHash('sha256').update(reproducibilityBytes).digest('hex'))
for(const row of categoryRows(r.tasks,r.execution.executed)) {
  const saved=r.categories[row.type]
  assert.equal(row.count,saved.taskCount)
  for(const status of ['PASS','FAIL','UNKNOWN']) assert.equal(row.counts[status]??0,saved[status])
}
assert.deepEqual(failureGroups(r.tasks).map(group=>group.members.length),[9,1,0])
assert.equal(filterTasks(r.tasks,'','FAILURE_DIAGNOSIS','FAIL').length,8)
const unknown=r.tasks.find(task=>task.benchmarkTaskId===r.limitation.taskId)
assert.equal(outcome(unknown),'UNKNOWN')
assert.match(r.limitation.reason,/expected_error_code/)
assert.deepEqual(r.tool,{required:41,invoked:41,miss:0})
assert.equal(r.provider.name,'Qwen'); assert.equal(r.provider.model,'qwen3.8-max')
assert.deepEqual([r.provider.provenCalls,r.provider.totalCalls,r.provider.mismatch,r.provider.fallback,r.provider.unproven],[83,83,0,0,0])
assert.deepEqual([r.execution.selected,r.execution.executed,r.execution.persisted,r.execution.missing,r.execution.duplicates],[105,105,105,0,0])
assert.equal(formatMetric({state:'VALUE',value:0,rate:0}),'0.0%')
for(const state of ['UNKNOWN','MISSING','ERROR']) assert.equal(formatMetric({state,value:0,rate:0}),state)
assert.equal(formatMetric({state:'NOT_APPLICABLE',value:0,rate:0}),'N/A')
for(const task of r.tasks) for(const forbidden of ['rawResponse','model','authProfile','principalId','formalEvidence','fixtureRefs','modelCallIds','toolResultObservations']) assert.ok(!(forbidden in task),forbidden)
assert.equal(/\bsk-[A-Za-z0-9]{20,}|Bearer\s+[A-Za-z0-9._-]{25,}/.test(JSON.stringify(r)),false,'No credential-like values in the public projection')
const page=fs.readFileSync(new URL('./BenchmarkPage.tsx',import.meta.url),'utf8')
assert.match(page,/nextRuns\.filter\(run => run\.evaluationRunId !== finalResultSummary\.evaluationRunId\)/)
assert.match(page,/selectedRunId === finalResultSummary\.evaluationRunId/)
assert.match(page,/controller\.signal\.aborted/)
const component=fs.readFileSync(new URL('./components/FinalBenchmarkOverview.tsx',import.meta.url),'utf8')
assert.doesNotMatch(component,/\b95\b|\b90\.48\b|\b91\.35\b|\b83\b/)
assert.match(component,/r\.reproducibility\.status/)
assert.match(component,/ui\('Reproducibility'\).*r\.reproducibility\.status/)
assert.doesNotMatch(component,/published\.reproducibility/)
const tab=fs.readFileSync(new URL('./components/BenchmarkTabContent.tsx',import.meta.url),'utf8')
assert.match(tab,/finalReport\.reproducibility\.status/)
const projection=fs.readFileSync(new URL('./projectFinalResult.mjs',import.meta.url),'utf8')
assert.doesNotMatch(projection,/reproducibility\s*:\s*['"]PASS['"]/)
console.log('PASS: official v5 counts/rates/splits/categories, legacy isolation, limitations, provider/integrity, availability, source minimization and revision pinning')
